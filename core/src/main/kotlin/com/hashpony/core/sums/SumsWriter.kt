package com.hashpony.core.sums

/** The formats HashPony can write. SFV is only valid for CRC32. */
enum class SumsOutputFormat { GNU, BSD_TAG, SFV }

/** One line to emit: a filename and its digest (hex, any case on input). */
data class WriteEntry(val name: String, val hex: String)

/**
 * Emits sums files that desktop `sha256sum -c`, `shasum -c` and `xxhsum -c`
 * accept byte for byte. GNU is the default (two-space separator, lowercase hex,
 * LF endings, names relative to the selected root); BSD tag and uppercase are
 * toggles; SFV is written when the algorithm is CRC32. Filenames containing
 * newlines or backslashes get the coreutils escape treatment, matching the
 * parser's read side.
 */
object SumsWriter {

    fun emit(
        algorithmId: String,
        entries: List<WriteEntry>,
        format: SumsOutputFormat,
        uppercase: Boolean = false,
    ): String = when (format) {
        SumsOutputFormat.GNU -> emitGnu(entries, uppercase)
        SumsOutputFormat.BSD_TAG -> emitBsd(algorithmId, entries, uppercase)
        SumsOutputFormat.SFV -> emitSfv(entries)
    }

    private fun emitGnu(entries: List<WriteEntry>, uppercase: Boolean): String {
        val sb = StringBuilder()
        for (e in entries) {
            val hex = if (uppercase) e.hex.uppercase() else e.hex.lowercase()
            val needsEscape = e.name.any { it == '\n' || it == '\r' || it == '\\' }
            if (needsEscape) sb.append('\\')
            sb.append(hex).append("  ").append(if (needsEscape) escapeName(e.name) else e.name).append('\n')
        }
        return sb.toString()
    }

    private fun emitBsd(algorithmId: String, entries: List<WriteEntry>, uppercase: Boolean): String {
        val label = tagLabel(algorithmId)
        val sb = StringBuilder()
        for (e in entries) {
            val hex = if (uppercase) e.hex.uppercase() else e.hex.lowercase()
            sb.append(label).append(" (").append(e.name).append(") = ").append(hex).append('\n')
        }
        return sb.toString()
    }

    private fun emitSfv(entries: List<WriteEntry>): String {
        val sb = StringBuilder()
        sb.append("; Generated by HashPony\n")
        for (e in entries) {
            // SFV convention is uppercase CRC, filename first.
            sb.append(e.name).append(' ').append(e.hex.uppercase()).append('\n')
        }
        return sb.toString()
    }

    /** coreutils escaping on write: `\`→`\\`, LF→`\n`, CR→`\r`. */
    private fun escapeName(name: String): String {
        val sb = StringBuilder(name.length + 4)
        for (c in name) {
            when (c) {
                '\\' -> sb.append("\\\\")
                '\n' -> sb.append("\\n")
                '\r' -> sb.append("\\r")
                else -> sb.append(c)
            }
        }
        return sb.toString()
    }

    /** A sensible file name for the save dialog. */
    fun suggestedFileName(
        algorithmId: String,
        format: SumsOutputFormat,
        entries: List<WriteEntry>,
        folderName: String? = null,
    ): String = when (format) {
        SumsOutputFormat.SFV -> "${folderName?.ifBlank { null } ?: "checksums"}.sfv"
        else -> if (entries.size == 1) {
            "${entries.first().name.substringAfterLast('/')}.${extension(algorithmId)}"
        } else {
            sumsSetName(algorithmId)
        }
    }

    private fun tagLabel(id: String): String = when (id) {
        "sha1" -> "SHA1"; "sha224" -> "SHA224"; "sha256" -> "SHA256"; "sha384" -> "SHA384"; "sha512" -> "SHA512"
        "sha3-224" -> "SHA3-224"; "sha3-256" -> "SHA3-256"; "sha3-384" -> "SHA3-384"; "sha3-512" -> "SHA3-512"
        "md5" -> "MD5"; "md4" -> "MD4"; "md2" -> "MD2"
        "ripemd160" -> "RIPEMD160"; "whirlpool" -> "WHIRLPOOL"; "sm3" -> "SM3"
        "streebog-256" -> "STREEBOG-256"; "streebog-512" -> "STREEBOG-512"
        "blake2b-512" -> "BLAKE2b"; "blake2b-256" -> "BLAKE2b-256"; "blake2s-256" -> "BLAKE2s"; "blake3-256" -> "BLAKE3"
        "keccak-256" -> "Keccak-256"
        "xxh32" -> "XXH32"; "xxh64" -> "XXH64"; "xxh3-64" -> "XXH3"; "xxh3-128" -> "XXH128"
        else -> id.uppercase()
    }

    private fun extension(id: String): String = when (id) {
        "sha256" -> "sha256"; "sha512" -> "sha512"; "sha384" -> "sha384"; "sha224" -> "sha224"; "sha1" -> "sha1"
        "md5" -> "md5"; "blake2b-512" -> "b2"; "crc32" -> "sfv"
        "xxh32" -> "xxh32"; "xxh64" -> "xxh64"; "xxh3-64" -> "xxh3"; "xxh3-128" -> "xxh128"
        else -> id
    }

    private fun sumsSetName(id: String): String = when (id) {
        "sha256" -> "SHA256SUMS"; "sha512" -> "SHA512SUMS"; "sha384" -> "SHA384SUMS"; "sha224" -> "SHA224SUMS"
        "sha1" -> "SHA1SUMS"; "md5" -> "MD5SUMS"; "blake2b-512" -> "B2SUMS"
        else -> "checksums.${extension(id)}"
    }
}
