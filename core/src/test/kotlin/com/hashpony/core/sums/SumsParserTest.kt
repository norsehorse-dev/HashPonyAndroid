package com.hashpony.core.sums

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Parser checks against fixtures captured verbatim from the real tools
 * (sha256sum/b2sum, shasum --tag, openssl 3.x, xxhsum, plus SFV and the
 * escaped-filename convention).
 */
class SumsParserTest {

    private val SHA_HELLO = "a948904f2f0f479b8f8197694b30184b0d2ed1c1cd2a1ec0fb85d299a192a447"
    private val SHA_NESTED = "414f8e9fd34ff68f66cbdab5ec63a5e738aa107f3454fa7edb51f49528abf9c6"

    @Test
    fun gnuTwoSpaceWithSubdirAndSpaces() {
        val text = "$SHA_HELLO  hello.txt\n$SHA_NESTED  sub/nested.txt\n" +
            "96faa18568f8de6d2be0927265d4f317324564b41ca02188ba5430234a87860d  my file.txt\n"
        val p = SumsParser.parse(text, "SHA256SUMS")
        assertEquals(SumsFormat.GNU, p.format)
        assertEquals(3, p.entries.size)
        assertEquals("hello.txt", p.entries[0].name)
        assertEquals(SHA_HELLO, p.entries[0].expectedHex)
        assertNull(p.entries[0].explicitAlgorithmId)
        assertEquals("sub/nested.txt", p.entries[1].name)
        assertEquals("my file.txt", p.entries[2].name)
    }

    @Test
    fun gnuBinaryMarker() {
        val p = SumsParser.parse("$SHA_HELLO *hello.txt\n")
        assertEquals(1, p.entries.size)
        assertTrue(p.entries[0].binary)
        assertEquals("hello.txt", p.entries[0].name)
    }

    @Test
    fun escapedFilename() {
        val p = SumsParser.parse("\\4bafe3aef45e40ddbe9a8bf31f1ada8adbc6df72769c3abc930f1baea750c917  a\\\\b.txt\n")
        assertEquals(1, p.entries.size)
        assertEquals("a\\b.txt", p.entries[0].name) // \\ unescaped to a single backslash
        assertFalse(p.entries[0].binary)
    }

    @Test
    fun bsdTag() {
        val text = "SHA256 (hello.txt) = $SHA_HELLO\n" +
            "SHA512 (hello.txt) = db3974a97f2407b7cae1ae637c0030687a11913274d578492558e39c16c017de84eacdc8c62fe34ee4e12b4b1428817f09b6a2760c3f8a664ceae94d2434a593\n" +
            "SHA1 (hello.txt) = 22596363b3de40b06f981fb85d82312e8c0ed511\n"
        val p = SumsParser.parse(text)
        assertEquals(SumsFormat.BSD_TAG, p.format)
        assertEquals(listOf("sha256", "sha512", "sha1"), p.entries.map { it.explicitAlgorithmId })
        assertTrue(p.entries.all { it.name == "hello.txt" })
    }

    @Test
    fun opensslPrefix() {
        val text = "SHA2-256(hello.txt)= $SHA_HELLO\nMD5(hello.txt)= 6f5902ac237024bdd0c176cb93063dc4\n"
        val p = SumsParser.parse(text)
        assertEquals(SumsFormat.OPENSSL, p.format)
        assertEquals(listOf("sha256", "md5"), p.entries.map { it.explicitAlgorithmId })
        assertEquals(SHA_HELLO, p.entries[0].expectedHex)
    }

    @Test
    fun xxhsumTagAllVariants() {
        val text = "XXH32 (hello.txt) = a4528db0\n" +
            "XXH64 (hello.txt) = 5215e13b207d6d8c\n" +
            "XXH128 (hello.txt) = eefac9d87100cd1336b2e733a5484425\n" +
            "XXH3 (hello.txt) = d42f7ed4b73c6bde\n"
        val p = SumsParser.parse(text)
        assertEquals(SumsFormat.XXHSUM_TAG, p.format)
        assertEquals(listOf("xxh32", "xxh64", "xxh3-128", "xxh3-64"), p.entries.map { it.explicitAlgorithmId })
    }

    @Test
    fun xxhsumDefaultIsGnuStyle() {
        val p = SumsParser.parse("5215e13b207d6d8c  hello.txt\n")
        assertEquals(1, p.entries.size)
        assertEquals("hello.txt", p.entries[0].name)
        assertEquals("5215e13b207d6d8c", p.entries[0].expectedHex)
        assertNull(p.entries[0].explicitAlgorithmId)
    }

    @Test
    fun sfvReversedOrderWithComment() {
        val text = "; generated by cksfv\nhello.txt AF083B2D\nsub/nested.txt 22945282\n"
        val p = SumsParser.parse(text, "files.sfv")
        assertEquals(SumsFormat.SFV, p.format)
        assertEquals(2, p.entries.size)
        assertEquals("hello.txt", p.entries[0].name)
        assertEquals("af083b2d", p.entries[0].expectedHex) // lowercased
        assertEquals("crc32", p.entries[0].explicitAlgorithmId)
    }

    @Test
    fun plainLoneAndNamed() {
        assertEquals("", SumsParser.parse("af083b2d\n").entries[0].name)
        val named = SumsParser.parse("af083b2d hello.txt\n")
        assertEquals("hello.txt", named.entries[0].name)
        assertEquals("af083b2d", named.entries[0].expectedHex)
    }

    @Test
    fun messyCommentsBlankCrlfAndMixedCase() {
        val text = "# a comment\r\n\r\n${SHA_HELLO.uppercase()}  hello.txt\r\n"
        val p = SumsParser.parse(text)
        assertEquals(1, p.entries.size)
        assertEquals(SHA_HELLO, p.entries[0].expectedHex) // lowercased, CR stripped
        assertEquals("hello.txt", p.entries[0].name)
    }
}
