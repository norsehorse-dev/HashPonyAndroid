package com.hashpony.core.sums

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.ByteArrayInputStream

/**
 * Writer tests. Exact-output assertions plus an emit→parse→verify round trip,
 * which is the release-gating check: what HashPony writes must read back and
 * verify cleanly. (The byte-for-byte acceptance by desktop `sha256sum -c`,
 * `shasum -c` and `xxhsum -c` is confirmed against the real tools in the build
 * pipeline; this suite reproduces the logic portably.)
 */
class SumsWriterTest {

    private val SHA_HELLO = "a948904f2f0f479b8f8197694b30184b0d2ed1c1cd2a1ec0fb85d299a192a447"
    private val SHA_NESTED = "414f8e9fd34ff68f66cbdab5ec63a5e738aa107f3454fa7edb51f49528abf9c6"
    private val CRC_HELLO = "af083b2d"

    private val twoEntries = listOf(
        WriteEntry("hello.txt", SHA_HELLO),
        WriteEntry("sub/nested.txt", SHA_NESTED),
    )

    @Test
    fun gnuDefaultIsTwoSpaceLowercaseLf() {
        val out = SumsWriter.emit("sha256", twoEntries, SumsOutputFormat.GNU)
        assertEquals(
            "$SHA_HELLO  hello.txt\n$SHA_NESTED  sub/nested.txt\n",
            out,
        )
    }

    @Test
    fun uppercaseToggle() {
        val out = SumsWriter.emit("sha256", listOf(twoEntries[0]), SumsOutputFormat.GNU, uppercase = true)
        assertEquals("${SHA_HELLO.uppercase()}  hello.txt\n", out)
    }

    @Test
    fun bsdTag() {
        val out = SumsWriter.emit("sha256", listOf(twoEntries[0]), SumsOutputFormat.BSD_TAG)
        assertEquals("SHA256 (hello.txt) = $SHA_HELLO\n", out)
        // xxHash tags use the exact xxhsum spellings
        assertEquals(
            "XXH3 (a) = 0011\n",
            SumsWriter.emit("xxh3-64", listOf(WriteEntry("a", "0011")), SumsOutputFormat.BSD_TAG),
        )
        assertEquals(
            "XXH128 (a) = 0011\n",
            SumsWriter.emit("xxh3-128", listOf(WriteEntry("a", "0011")), SumsOutputFormat.BSD_TAG),
        )
    }

    @Test
    fun sfvHasCommentHeaderAndUppercaseCrc() {
        val out = SumsWriter.emit("crc32", listOf(WriteEntry("hello.txt", CRC_HELLO)), SumsOutputFormat.SFV)
        assertEquals("; Generated by HashPony\nhello.txt ${CRC_HELLO.uppercase()}\n", out)
    }

    @Test
    fun escapedFilenameOnWrite() {
        val out = SumsWriter.emit("sha256", listOf(WriteEntry("a\\b.txt", SHA_HELLO)), SumsOutputFormat.GNU)
        assertEquals("\\$SHA_HELLO  a\\\\b.txt\n", out) // leading backslash + \\ escape
        // and it reads back to the original name
        val parsed = SumsParser.parse(out)
        assertEquals("a\\b.txt", parsed.entries[0].name)
    }

    @Test
    fun suggestedNames() {
        assertEquals("SHA256SUMS", SumsWriter.suggestedFileName("sha256", SumsOutputFormat.GNU, twoEntries))
        assertEquals("hello.txt.sha256", SumsWriter.suggestedFileName("sha256", SumsOutputFormat.GNU, listOf(twoEntries[0])))
        assertEquals("nested.txt.sha256", SumsWriter.suggestedFileName("sha256", SumsOutputFormat.GNU, listOf(twoEntries[1])))
        assertEquals("B2SUMS", SumsWriter.suggestedFileName("blake2b-512", SumsOutputFormat.GNU, twoEntries))
        assertEquals("Downloads.sfv", SumsWriter.suggestedFileName("crc32", SumsOutputFormat.SFV, twoEntries, "Downloads"))
    }

    @Test
    fun emitParseVerifyRoundTrip() {
        val files = mapOf(
            "hello.txt" to "hello world\n".toByteArray(),
            "sub/nested.txt" to "nested file\n".toByteArray(),
        )
        for (format in listOf(SumsOutputFormat.GNU, SumsOutputFormat.BSD_TAG)) {
            val text = SumsWriter.emit("sha256", twoEntries, format)
            val parsed = SumsParser.parse(text, "SHA256SUMS")
            val report = SumsVerifier.verify(parsed, "SHA256SUMS", setOf("sha256"), { n -> files[n]?.let { ByteArrayInputStream(it) } })
            assertTrue("round trip failed for $format", report.allOk)
            assertEquals(2, report.ok)
        }
        // SFV round trip
        val sfv = SumsWriter.emit("crc32", listOf(WriteEntry("hello.txt", CRC_HELLO)), SumsOutputFormat.SFV)
        val parsed = SumsParser.parse(sfv, "checksums.sfv")
        val report = SumsVerifier.verify(parsed, "checksums.sfv", setOf("sha256"), { n -> files[n]?.let { ByteArrayInputStream(it) } })
        assertTrue(report.allOk)
    }
}
